$ErrorActionPreference = 'Stop'

$baseUrl = if ($env:BAKE_RELEASE_BASE_URL) { $env:BAKE_RELEASE_BASE_URL.TrimEnd('/') } else { 'https://bake.justar.dev' }
$installRoot = if ($env:BAKE_INSTALL_ROOT) { $env:BAKE_INSTALL_ROOT } else { Join-Path $env:LOCALAPPDATA 'Bake' }
# Written into the launcher, so it must not depend on the directory the installer ran from.
$installRoot = [IO.Path]::GetFullPath($installRoot)
$binDir = if ($env:BAKE_BIN_DIR) { $env:BAKE_BIN_DIR } else { Join-Path $installRoot 'bin' }

if (-not [Environment]::Is64BitOperatingSystem -or $env:PROCESSOR_ARCHITECTURE -ne 'AMD64') {
  throw 'This Windows platform has no Bake release archive.'
}
try { $nodeMajor = [int]((& node -p 'process.versions.node').Trim().Split('.')[0]) }
catch { throw 'Bake install needs Node.js 24 or newer on PATH.' }
if ($nodeMajor -lt 24) { throw 'Bake install needs Node.js 24 or newer on PATH.' }
if (-not (Get-Command tar.exe -ErrorAction SilentlyContinue)) { throw 'Bake install needs Windows tar.exe.' }

$temporary = Join-Path ([IO.Path]::GetTempPath()) ("bake-install-" + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $temporary | Out-Null
$animation = $null
$previousProgressPreference = $ProgressPreference
$ProgressPreference = 'SilentlyContinue'
$progressPath = Join-Path $temporary 'progress'
function Set-BakeStage([string]$Stage) {
  [IO.File]::WriteAllText($progressPath, $Stage, [Text.Encoding]::ASCII)
}
function Stop-BakeAnimation([string]$Stage) {
  if ($null -ne $script:animation) {
    Set-BakeStage $Stage
    $script:animation.WaitForExit()
    $script:animation.Dispose()
    $script:animation = $null
  }
}
try {
  if (-not [Console]::IsErrorRedirected -and $env:TERM -ne 'dumb' -and -not $env:CI -and $env:BAKE_NO_ANIMATION -ne '1') {
    $animationPath = Join-Path $temporary 'bakery.cjs'
    Set-Content -Path $animationPath -Encoding Ascii -Value @'
// Generated by bun scripts/release/embed-animation.ts.
// # BEGIN BAKERY
var I=require("node:fs");function h(e,r,_){let a=e.isTTY===!0&&r.TERM!=="dumb"&&!r.CI&&r.BAKE_NO_ANIMATION!=="1",s=r.NO_COLOR===void 0,l=_,f=0,o=!1,d=!1,u=["[##  _____  ##]","[##  (___)  ##]","[## (~~~~~) ##]","[## (~~~~~) ##]"],g=[". . "," : .",". : "," . :"],m=()=>(e.columns!==void 0&&e.columns>0?e.columns:80)-1,p=()=>{let t=Math.floor(f++/3)%u.length,i=`  ${u[t]} ${g[f%g.length]} ${l}`.slice(0,m());e.write(`\r\x1B[2K${s?"\x1B[38;5;215m":""}${i}${s?"\x1B[0m":""}`),d=!0};if(a)p();let b=a?setInterval(p,180):void 0;return b?.unref(),{stage(t){if(!o)l=t},finish(t=!1){if(o)return;if(o=!0,clearInterval(b),!d)return;if(e.write("\r\x1B[2K"),t){let i="  (~~~~~)  Freshly baked.".slice(0,m());e.write(`${s?"\x1B[38;5;215m":""}${i}${s?"\x1B[0m":""}
`)}}}}var x=process.argv[2];if(!x)throw Error("Missing installer progress file");var v=Number(process.argv[3]),n=h(process.stderr,process.env,"Warming the oven..."),c=setInterval(()=>{try{process.kill(v,0);let e=I.readFileSync(x,"utf8").trim();if(e==="done"||e==="stop")clearInterval(c),n.finish(e==="done");else if(e)n.stage(e)}catch{clearInterval(c),n.finish()}},100);for(let e of["SIGINT","SIGTERM"])process.once(e,()=>{clearInterval(c),n.finish()});
// # END BAKERY
'@
    Set-BakeStage 'Checking the recipe...'
    $animation = Start-Process -FilePath (Get-Command node).Source -ArgumentList @(('"' + $animationPath + '"'), ('"' + $progressPath + '"'), "$PID") -NoNewWindow -PassThru
  }
  # The signature covers the manifest's exact bytes, so both are saved as
  # served and checked before either is parsed.
  $manifestPath = Join-Path $temporary 'latest.json'
  $signaturePath = Join-Path $temporary 'latest.json.sig'
  Invoke-WebRequest "$baseUrl/latest.json" -UseBasicParsing -OutFile $manifestPath
  Invoke-WebRequest "$baseUrl/latest.json.sig" -UseBasicParsing -OutFile $signaturePath
  $verifier = Join-Path $temporary 'verify.cjs'
  Set-Content -Path $verifier -Encoding Ascii -Value @'
const fs = require('node:fs')
const crypto = require('node:crypto')
// The release signing key; BAKE_RELEASE_PUBLIC_KEY adds one for a local check.
const keys = ['MCowBQYDK2VwAyEAG1Z33Mis04XnFsekLrnPDBwSgn26uNeLz3XtGal+xC4=', process.env.BAKE_RELEASE_PUBLIC_KEY]
  .filter(key => typeof key === 'string' && key.trim() !== '')
const bytes = fs.readFileSync(process.argv[2])
const signature = Buffer.from(fs.readFileSync(process.argv[3], 'utf8').trim(), 'base64')
const signed = signature.length === 64 && keys.some(key => {
  try { return crypto.verify(null, bytes, crypto.createPublicKey({ key: Buffer.from(key.trim(), 'base64'), format: 'der', type: 'spki' }), signature) } catch { return false }
})
