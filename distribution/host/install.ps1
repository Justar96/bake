'@
  & node $verifier $manifestPath $signaturePath
  if ($LASTEXITCODE -ne 0) { throw 'The Bake release manifest signature did not verify.' }
  $manifest = Get-Content -Raw -Path $manifestPath | ConvertFrom-Json
  $version = [string]$manifest.version
  $artifact = $manifest.artifacts.'win32-x64'
  if ($version -notmatch '^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$' -or
      -not $artifact -or
      [string]$artifact.file -ne "bake-v$version-win32-x64.tar.gz" -or
      [string]$artifact.sha256 -notmatch '^[a-f0-9]{64}$') {
    throw 'No valid Bake archive for win32-x64.'
  }
  $archive = Join-Path $temporary $artifact.file
  # A GitHub host serves each archive from its own tag; see archiveUrl in the updater.
  $archiveUrl = if ($baseUrl -match '^(https://github\.com/[^/]+/[^/]+/releases)/latest/download$') {
    "$($Matches[1])/download/v$version/$($artifact.file)"
  } else { "$baseUrl/releases/$version/$($artifact.file)" }
  Set-BakeStage 'Gathering ingredients...'
  Invoke-WebRequest $archiveUrl -UseBasicParsing -OutFile $archive
  Set-BakeStage 'Checking ingredients...'
  $actual = (Get-FileHash -Algorithm SHA256 $archive).Hash.ToLowerInvariant()
  if ($actual -ne $artifact.sha256) { throw 'Bake download checksum did not match the release manifest.' }
  Set-BakeStage 'Baking your release...'
  $unpacked = Join-Path $temporary 'unpacked'
  New-Item -ItemType Directory -Path $unpacked | Out-Null
  & tar.exe -xzf $archive -C $unpacked
  if ($LASTEXITCODE -ne 0) { throw 'Could not extract the Bake archive.' }
  & node (Join-Path $unpacked 'apps\cli\lib\bin.js') --version | Out-Null
  if ($LASTEXITCODE -ne 0) { throw 'The Bake archive did not start.' }

  $versions = Join-Path $installRoot 'versions'
  New-Item -ItemType Directory -Force -Path $versions, $binDir | Out-Null
  $digestPrefix = ([string]$artifact.sha256).Substring(0, 12)
  $versionPath = Join-Path $versions "$version-$digestPrefix"
  if (Test-Path $versionPath) {
    & node (Join-Path $versionPath 'apps\cli\lib\bin.js') --version | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'The existing Bake installation did not start.' }
  } else {
    Move-Item $unpacked $versionPath
  }
  # The pointer names the current release; `bake update` moves it the same
  # way, by replacing the whole file.
  $pointer = Join-Path $installRoot 'current.txt'
  $pointerNext = "$pointer.$PID.tmp"
  [IO.File]::WriteAllText($pointerNext, "$version-$digestPrefix`r`n", [Text.Encoding]::ASCII)
  Move-Item -Force -LiteralPath $pointerNext -Destination $pointer
  # The launcher reads that pointer, so no update ever rewrites it; the
  # release ships its text, the same text the updater writes.
  $template = Join-Path $versionPath 'bin\bake-launcher.cmd.template'
  if (-not (Test-Path $template)) { throw 'The Bake archive has no launcher template.' }
  $commandText = [IO.File]::ReadAllText($template).Replace('@@BAKE_RELEASE_ROOT@@', $installRoot.Replace('%', '%%'))
  $cmd = Join-Path $binDir 'bake.cmd'
  [IO.File]::WriteAllText($cmd, $commandText, [Text.Encoding]::ASCII)
  if ($env:BAKE_SKIP_PATH_UPDATE -ne '1') {
    $pathParts = [Environment]::GetEnvironmentVariable('Path', 'User') -split ';'
    if ($pathParts -notcontains $binDir) {
      $existing = [Environment]::GetEnvironmentVariable('Path', 'User')
      [Environment]::SetEnvironmentVariable('Path', (($existing.TrimEnd(';') + ';' + $binDir).TrimStart(';')), 'User')
    }
  }
  $env:Path += ";$binDir"
  Stop-BakeAnimation done
  Write-Output "Installed Bake $version at $versionPath. Run: bake"
} finally {
  Stop-BakeAnimation stop
  $ProgressPreference = $previousProgressPreference
  Remove-Item -Recurse -Force $temporary -ErrorAction SilentlyContinue
}
