#!/bin/sh
set -eu

base_url=${BAKE_RELEASE_BASE_URL:-https://bake.justar.dev}
install_root=${BAKE_INSTALL_ROOT:-"$HOME/.local/share/bake"}
bin_dir=${BAKE_BIN_DIR:-"$HOME/.local/bin"}

command -v curl >/dev/null 2>&1 || { echo 'Bake install needs curl.' >&2; exit 1; }
command -v tar >/dev/null 2>&1 || { echo 'Bake install needs tar.' >&2; exit 1; }
command -v node >/dev/null 2>&1 || { echo 'Bake install needs Node.js 24 or newer.' >&2; exit 1; }
node -e 'process.exit(Number(process.versions.node.split(".")[0]) >= 24 ? 0 : 1)' || {
  echo 'Bake install needs Node.js 24 or newer.' >&2
  exit 1
}

case "$(uname -s)-$(uname -m)" in
  Darwin-arm64) target=darwin-arm64 ;;
  Darwin-x86_64) target=darwin-x64 ;;
  Linux-aarch64|Linux-arm64) target=linux-arm64 ;;
  Linux-x86_64) target=linux-x64 ;;
  *) echo 'This platform has no Bake release archive.' >&2; exit 1 ;;
esac

temporary=$(mktemp -d "${TMPDIR:-/tmp}/bake-install.XXXXXX")
animation_pid=
stop_animation() {
  if [ -n "$animation_pid" ]; then
    printf '%s\n' "$1" > "$temporary/progress"
    wait "$animation_pid" 2>/dev/null || :
    animation_pid=
  fi
}
cleanup() {
  stop_animation stop
  if [ -f "$temporary/errors" ]; then cat "$temporary/errors" >&2; fi
  rm -rf "$temporary"
}
trap cleanup EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM
if [ -t 2 ] && [ "${TERM:-}" != dumb ] && [ -z "${CI:-}" ] && [ "${BAKE_NO_ANIMATION:-}" != 1 ]; then
  cat > "$temporary/bakery.cjs" <<'BAKERY'
// Generated by bun scripts/release/embed-animation.ts.
// # BEGIN BAKERY
var R=require("node:fs");var h=["#f5e6c4","#f0d49a","#e8ba68","#dc9c3f","#c97f2a","#ab621f","#8b4a17"];var g=120,y=3,C="\u2584\u2586\u2588\u2588\u2588\u2586\u2584",d=[".",":","=","#"],p=6,O=[[1,2,4,64],[8,16,32,128]],L=Array.from({length:p*2},(e,t)=>Array.from({length:y},(r,n)=>{let o=(t+n*2)%p,a=t+n>>1&1,s=0;for(let[c,i]of[[0,o],[1,o-1]]){if(i<0||i>3)continue;s|=O[a+c&1][3-i]}return String.fromCodePoint(10240+s)}).join("")),P=[".",":","'","`"," "," "],A=Array.from({length:p},(e,t)=>Array.from({length:y},(r,n)=>P[(t+n*2)%p]).join(""));function _(e){let t=Math.min(1,Math.max(0,Number.isFinite(e)?e:0));return h[Math.round(t*(h.length-1))]}function S(e,t,r){let n=Math.floor(Math.max(0,e)/g),o=_(t);if(r==="unicode")return{steam:L[n%L.length],loaf:C,tone:o};let a=d[Math.min(d.length-1,Math.floor(Math.min(1,Math.max(0,t))*d.length))];return{steam:A[n%A.length],loaf:`(${a.repeat(5)})`,tone:o}}function F(e){return{steam:" ".repeat(y),loaf:e==="unicode"?C:`(${d.at(-1).repeat(5)})`,tone:_(1)}}function I(e){let t=[e.LC_ALL,e.LC_CTYPE,e.LANG].find((r)=>r!==void 0&&r!=="")?.toLowerCase();if(t===void 0||!/utf-?8/.test(t))return"ascii";if(e.TERM===void 0||e.TERM===""||e.TERM==="dumb")return"ascii";return/^(zh|ja|ko)/.test(t)?"ascii":"unicode"}function G(e){let t=[0,95,135,175,215,255],r=(s)=>t.reduce((c,i,l)=>Math.abs(i-s)<Math.abs(t[c]-s)?l:c,0),[n,o,a]=[1,3,5].map((s)=>r(Number.parseInt(e.slice(s,s+2),16)));return 16+36*n+6*o+a}function b(e,t,r){let n=`  ${e.steam} ${e.loaf}  `,o=Math.max(0,r.width-n.length),a=[...t].length>o?`${[...t].slice(0,Math.max(0,o-1)).join("")}${o>0?"\u2026":""}`:t;if(n.length>r.width)return"";if(!r.color)return`${n}${a}`;return`  \x1B[2m${e.steam}\x1B[22m \x1B[38;5;${G(e.tone)}m${e.loaf}\x1B[39m  ${a}`}var B=0.8,D=20000;function k(e,t,r){let n=e.isTTY===!0&&t.TERM!=="dumb"&&!t.CI&&t.BAKE_NO_ANIMATION!=="1",o=t.NO_COLOR===void 0,a=I(t),s=Date.now(),c=r,i,l=!1,T=!1,E=()=>(e.columns!==void 0&&e.columns>0?e.columns:80)-1,M=()=>{let f=Date.now()-s,u=i??B*(1-Math.exp(-f/D));e.write(`\r\x1B[2K${b(S(f,u,a),c,{color:o,width:E()})}`),T=!0};if(n)M();let w=n?setInterval(M,g):void 0;return w?.unref(),{stage(f,u){if(l)return;if(c=f,u!==void 0)i=u},finish(f=!1){if(l)return;if(l=!0,clearInterval(w),!T)return;if(e.write("\r\x1B[2K"),f)e.write(`${b(F(a),"Freshly baked.",{color:o,width:E()})}
`)}}}var N=process.argv[2];if(!N)throw Error("Missing installer progress file");var v=Number(process.argv[3]),m=k(process.stderr,process.env,"Warming the oven..."),x=setInterval(()=>{try{process.kill(v,0);let e=R.readFileSync(N,"utf8").trim();if(e==="done"||e==="stop")clearInterval(x),m.finish(e==="done");else if(e)m.stage(e)}catch{clearInterval(x),m.finish()}},100);for(let e of["SIGINT","SIGTERM"])process.once(e,()=>{clearInterval(x),m.finish()});
// # END BAKERY
BAKERY
  printf '%s\n' 'Checking the recipe...' > "$temporary/progress"
  node "$temporary/bakery.cjs" "$temporary/progress" "$$" &
  animation_pid=$!
fi
install_bake() {
curl -fsSL "$base_url/latest.json" -o "$temporary/latest.json"
curl -fsSL "$base_url/latest.json.sig" -o "$temporary/latest.json.sig"
node - "$temporary/latest.json" "$target" "$temporary/latest.json.sig" > "$temporary/selected" <<'NODE'
const fs = require('node:fs')
const crypto = require('node:crypto')
// The release signing key; BAKE_RELEASE_PUBLIC_KEY adds one for a local check.
const keys = ['MCowBQYDK2VwAyEAG1Z33Mis04XnFsekLrnPDBwSgn26uNeLz3XtGal+xC4=', process.env.BAKE_RELEASE_PUBLIC_KEY]
  .filter(key => typeof key === 'string' && key.trim() !== '')
const bytes = fs.readFileSync(process.argv[2])
const signature = Buffer.from(fs.readFileSync(process.argv[4], 'utf8').trim(), 'base64')
const signed = signature.length === 64 && keys.some(key => {
  try { return crypto.verify(null, bytes, crypto.createPublicKey({ key: Buffer.from(key.trim(), 'base64'), format: 'der', type: 'spki' }), signature) } catch { return false }
})
if (!signed) {
  console.error('The Bake release manifest signature did not verify.')
  process.exit(1)
}
const manifest = JSON.parse(bytes.toString('utf8'))
const target = process.argv[3]
const artifact = manifest.artifacts?.[target]
if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(manifest.version)
  || artifact?.file !== `bake-v${manifest.version}-${target}.tar.gz`
  || !/^[a-f0-9]{64}$/.test(artifact.sha256)) {
  console.error(`No valid Bake archive for ${target}`)
  process.exit(1)
}
console.log(manifest.version)
console.log(artifact.file)
console.log(artifact.sha256)
NODE
version=$(sed -n '1p' "$temporary/selected")
file=$(sed -n '2p' "$temporary/selected")
expected=$(sed -n '3p' "$temporary/selected")
# A GitHub host serves each archive from its own tag; see archiveUrl in the updater.
case $base_url in
  https://github.com/*/*/releases/latest/download) archive_url="${base_url%/latest/download}/download/v$version/$file" ;;
  *) archive_url="$base_url/releases/$version/$file" ;;
esac
printf '%s\n' 'Gathering ingredients...' > "$temporary/progress"
curl -fsSL "$archive_url" -o "$temporary/$file"
printf '%s\n' 'Checking ingredients...' > "$temporary/progress"
if command -v shasum >/dev/null 2>&1; then
  actual=$(shasum -a 256 "$temporary/$file" | cut -d ' ' -f 1)
elif command -v sha256sum >/dev/null 2>&1; then
  actual=$(sha256sum "$temporary/$file" | cut -d ' ' -f 1)
else
  echo 'Bake install needs shasum or sha256sum.' >&2
  exit 1
fi
if [ "$actual" != "$expected" ]; then
  echo 'Bake download checksum did not match the release manifest.' >&2
  exit 1
fi

printf '%s\n' 'Baking your release...' > "$temporary/progress"
mkdir -p "$install_root/versions" "$bin_dir" "$temporary/unpacked"
tar -xzf "$temporary/$file" -C "$temporary/unpacked"
node "$temporary/unpacked/apps/cli/lib/bin.js" --version >/dev/null
digest_prefix=$(printf '%s' "$expected" | cut -c 1-12)
new_version="$install_root/versions/$version-$digest_prefix"
if [ -d "$new_version" ]; then
  node "$new_version/apps/cli/lib/bin.js" --version >/dev/null
else
  mv "$temporary/unpacked" "$new_version"
fi
ln -s "$new_version" "$install_root/.current-$$"
if [ -L "$install_root/current" ]; then
  rm "$install_root/current"
elif [ -e "$install_root/current" ]; then
  echo "$install_root/current exists and is not a Bake-managed link." >&2
  exit 1
fi
mv -f "$install_root/.current-$$" "$install_root/current"
ln -s "$install_root/current/bin/bake" "$bin_dir/.bake-$$"
if [ -L "$bin_dir/bake" ]; then
  rm "$bin_dir/bake"
elif [ -e "$bin_dir/bake" ]; then
  echo "$bin_dir/bake exists and is not a Bake-managed link." >&2
  exit 1
fi
mv -f "$bin_dir/.bake-$$" "$bin_dir/bake"

}
install_bake 2> "$temporary/errors"
stop_animation 'done'

echo "Installed Bake $version at $new_version"
case ":$PATH:" in
  *":$bin_dir:"*) echo 'Run: bake' ;;
  *) echo "Add $bin_dir to PATH, then run: bake" ;;
esac
